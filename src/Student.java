public class Student {

    String name;
    int age;
    String branch;
    String usn;

    Student() {

    }

    Student (String name, int age, String branch, String usn) {

        this.name = name;
        this.age = age;
        this.branch = branch;
        this.usn = usn;
    }

    Student(String name) {

        this.name = name;
    }
}
